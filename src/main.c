// Envio de comando via SPI
static void lcd_cmd(uint8_t cmd) {
    gpio_pin_set_dt(&dc_gpio, 0);
    struct spi_buf buf = {.buf = &cmd, .len = 1};
    struct spi_buf_set tx = {.buffers = &buf, .count = 1};
    spi_write_dt(&spi_spec, &tx);
}

// Envio de dados via SPI
static void lcd_data(const uint8_t *data, size_t len) {
    if (len == 0) return;
    gpio_pin_set_dt(&dc_gpio, 1);
    struct spi_buf buf = {.buf = (void *)data, .len = len};
    struct spi_buf_set tx = {.buffers = &buf, .count = 1};
    spi_write_dt(&spi_spec, &tx);
}

static void lcd_data_byte(uint8_t data) {
    lcd_data(&data, 1);
}

// Inicialização INITR_BLACKTAB
static void st7735_init_blacktab(void) {
    gpio_pin_set_dt(&rst_gpio, 1);
    k_msleep(10);
    gpio_pin_set_dt(&rst_gpio, 0);
    k_msleep(10);
    gpio_pin_set_dt(&rst_gpio, 1);
    k_msleep(150);

    lcd_cmd(ST7735_SWRESET);
    k_msleep(150);

    lcd_cmd(ST7735_SLPOUT);
    k_msleep(500);

    lcd_cmd(ST7735_COLMOD);
    lcd_data_byte(0x05);
    k_msleep(10);

    lcd_cmd(ST7735_MADCTL);
    lcd_data_byte(0xC8);

    lcd_cmd(ST7735_NORON);
    k_msleep(10);

    lcd_cmd(ST7735_DISPON);
    k_msleep(100);
}

// Preenche um retângulo
static void lcd_fill_rect(int x, int y, int w, int h, uint16_t color) {
    lcd_cmd(ST7735_CASET);
    uint8_t caset[] = {0x00, (uint8_t)x, 0x00, (uint8_t)(x + w - 1)};
    lcd_data(caset, 4);

    lcd_cmd(ST7735_RASET);
    uint8_t raset[] = {0x00, (uint8_t)y, 0x00, (uint8_t)(y + h - 1)};
    lcd_data(raset, 4);

    lcd_cmd(ST7735_RAMWR);

    uint8_t pix[2] = { (uint8_t)(color >> 8), (uint8_t)(color & 0xFF) };
    for (int i = 0; i < (w * h); i++) {
        lcd_data(pix, 2);
    }
}

// Desenha 1 caractere individual
static void lcd_draw_char(int x, int y, char c, uint16_t color, uint16_t bg, uint8_t size) {
    if (c < 32 || c > 122) c = '?';

    const uint8_t *char_bitmap = &font5x7[(c - 32) * 5];

    for (int i = 0; i < 5; i++) {
        uint8_t line = char_bitmap[i];
        for (int j = 0; j < 8; j++) {
            if (line & 0x01) {
                lcd_fill_rect(x + (i * size), y + (j * size), size, size, color);
            } else if (bg != color) {
                lcd_fill_rect(x + (i * size), y + (j * size), size, size, bg);
            }
            line >>= 1;
        }
    }
    if (bg != color) {
        lcd_fill_rect(x + (5 * size), y, size, 8 * size, bg);
    }
}

// Desenha uma String completa
static void lcd_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg, uint8_t size) {
    int cur_x = x;
    int cur_y = y;

    while (*str) {
        if (*str == '\n') {
            cur_y += size * 8;
            cur_x = x;
        } else {
            lcd_draw_char(cur_x, cur_y, *str, color, bg, size);
            cur_x += size * 6;
        }
        str++;
    }
}

int main(void) {
    LOG_INF("Iniciando Display ST7735 no Zephyr RTOS...");

    if (!spi_is_ready_dt(&spi_spec) || !gpio_is_ready_dt(&dc_gpio) || !gpio_is_ready_dt(&rst_gpio)) {
        LOG_ERR("Erro nos periféricos SPI/GPIO!");
        return 0;
    }

    gpio_pin_configure_dt(&dc_gpio, GPIO_OUTPUT_INACTIVE);
    gpio_pin_configure_dt(&rst_gpio, GPIO_OUTPUT_ACTIVE);

    st7735_init_blacktab();

    // Limpa a tela com fundo PRETO
    lcd_fill_rect(0, 0, LCD_WIDTH, LCD_HEIGHT, COLOR_BLACK);

    // ========================================================================
    // ESCREVENDO TEXTO NA TELA
    // ========================================================================
    
    // Texto Azul tamanho 2 ("Hello")
    lcd_draw_string(5, 30, "Hello", COLOR_BLUE, COLOR_BLACK, 2);

    // Texto Branco tamanho 2 ("World!")
    lcd_draw_string(5, 55, "World!", COLOR_WHITE, COLOR_BLACK, 2);

    // Texto Verde tamanho 1 ("Zephyr RTOS")
    lcd_draw_string(5, 90, "Zephyr RTOS v4.3", COLOR_GREEN, COLOR_BLACK, 1);

    LOG_INF("Texto enviado para a tela!");

    while (1) {
        k_msleep(1000);
    }

    return 0;
}