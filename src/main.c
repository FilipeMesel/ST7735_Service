static void lcd_cmd(uint8_t cmd) {
    gpio_pin_set_dt(&dc_gpio, 0);
    struct spi_buf buf = {.buf = &cmd, .len = 1};
    struct spi_buf_set tx = {.buffers = &buf, .count = 1};
    spi_write_dt(&spi_spec, &tx);
}

static void lcd_data(const uint8_t *data, size_t len) {
    if (len == 0) return;
    gpio_pin_set_dt(&dc_gpio, 1);
    struct spi_buf buf = {.buf = (void *)data, .len = len};
    struct spi_buf_set tx = {.buffers = &buf, .count = 1};
    spi_write_dt(&spi_spec, &tx);
}

static void st7735_init_blacktab(void) {
    gpio_pin_set_dt(&rst_gpio, 1);
    k_msleep(10);
    gpio_pin_set_dt(&rst_gpio, 0);
    k_msleep(10);
    gpio_pin_set_dt(&rst_gpio, 1);
    k_msleep(150);

    lcd_cmd(ST7735_SWRESET);
    k_msleep(150);

    lcd_cmd(ST7735_SLPOUT);
    k_msleep(500);

    lcd_cmd(ST7735_COLMOD);
    uint8_t format = 0x05;
    lcd_data(&format, 1);
    k_msleep(10);

    lcd_cmd(ST7735_MADCTL);
    uint8_t madctl = 0xC8;
    lcd_data(&madctl, 1);

    lcd_cmd(ST7735_NORON);
    k_msleep(10);

    lcd_cmd(ST7735_DISPON);
    k_msleep(100);
}


int main(void) {
    LOG_INF("Iniciando Aplicação de Layout...");

    if (ui_engine_init() != 0) {
        LOG_ERR("Erro ao inicializar UI Engine!");
        return 0;
    }

    // Instancia o layout de 3 regiões
    ui_layout_t main_layout;
    ui_layout_init_standard(&main_layout);

    // 1. PRIMEIRO: Preenche o fundo de todas as áreas
    lcd_fill_rect(main_layout.header.x, main_layout.header.y, 
                  main_layout.header.width, main_layout.header.height, COLOR_YELLOW);

    lcd_fill_rect(main_layout.content.x, main_layout.content.y, 
                  main_layout.content.width, main_layout.content.height, COLOR_BLACK);

    lcd_fill_rect(main_layout.footer.x, main_layout.footer.y, 
                  main_layout.footer.width, main_layout.footer.height, COLOR_GREEN);

    // 2. SEGUNDO: Desenha os textos sobre os fundos
    ui_draw_header(&main_layout, "SYSTEM PANEL", COLOR_WHITE, COLOR_BLUE);
    
    lcd_draw_string(10, 70, "Content Area", COLOR_WHITE, COLOR_BLACK, 1);
    lcd_draw_string(10, 85, "128x120 Pixels", COLOR_GREEN, COLOR_BLACK, 1);

    ui_draw_footer(&main_layout, "STATUS: READY", COLOR_YELLOW, COLOR_GREEN);

    LOG_INF("Layout renderizado!");

    while (1) {
        k_msleep(1000);
    }

    return 0;
}